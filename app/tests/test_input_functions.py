def test_tai_from_tgcndb_known_organism():
    weights = tai_from_tgcnDB("Escherichia coli")
    assert weights.keys() == EXPECTED_ECOLI_TAI_WEIGHTS.keys()
    for codon, expected_value in EXPECTED_ECOLI_TAI_WEIGHTS.items():
        assert weights[codon] == pytest.approx(expected_value)


def test_tai_from_tgcndb_unknown_organism_returns_empty_dict():
    assert tai_from_tgcnDB("Not A Real Organism Name") == {}
